//! `FreeType2` build script. On normal targets we find it externally.
//! WebAssembly has no system libraries, so there we compile the vendored
//! sources.

use std::{env, path::PathBuf};
use tectonic_dep_support::{target_is_wasm, wasm_vendor_dir, Configuration, Dependency, Spec};

struct Freetype2Spec;

impl Spec for Freetype2Spec {
    fn get_pkgconfig_spec(&self) -> &str {
        "freetype2"
    }

    fn get_vcpkg_spec(&self) -> &[&str] {
        &["freetype"]
    }
}

/// FreeType's per-module amalgamation files, as listed in its `docs/INSTALL.ANY`.
///
/// This is the full stock module set minus the ones no TeX document can reach:
/// the bitmap-only font formats (BDF, PCF, PFR, Windows FNT), the bzip2 and LZW
/// stream filters, and the SDF and SVG renderers.
const FREETYPE_SOURCES: &[&str] = &[
    "src/autofit/autofit.c",
    "src/base/ftbase.c",
    "src/base/ftbbox.c",
    "src/base/ftbitmap.c",
    "src/base/ftdebug.c",
    "src/base/ftfstype.c",
    "src/base/ftgasp.c",
    "src/base/ftglyph.c",
    "src/base/ftinit.c",
    "src/base/ftmm.c",
    "src/base/ftstroke.c",
    "src/base/ftsynth.c",
    "src/base/ftsystem.c",
    "src/base/fttype1.c",
    "src/cache/ftcache.c",
    "src/cff/cff.c",
    "src/cid/type1cid.c",
    "src/gzip/ftgzip.c",
    "src/psaux/psaux.c",
    "src/pshinter/pshinter.c",
    "src/psnames/psnames.c",
    "src/raster/raster.c",
    "src/sfnt/sfnt.c",
    "src/smooth/smooth.c",
    "src/truetype/truetype.c",
    "src/type1/type1.c",
];

/// The modules `ftinit.c` should register, replacing the stock `ftmodule.h` so
/// it matches the trimmed source list above.
const FTMODULE_H: &str = r#"/* Generated by tectonic_bridge_freetype2's build script for the wasm build. */
FT_USE_MODULE( FT_Module_Class, autofit_module_class )
FT_USE_MODULE( FT_Driver_ClassRec, tt_driver_class )
FT_USE_MODULE( FT_Driver_ClassRec, t1_driver_class )
FT_USE_MODULE( FT_Driver_ClassRec, cff_driver_class )
FT_USE_MODULE( FT_Driver_ClassRec, t1cid_driver_class )
FT_USE_MODULE( FT_Module_Class, psaux_module_class )
FT_USE_MODULE( FT_Module_Class, psnames_module_class )
FT_USE_MODULE( FT_Module_Class, pshinter_module_class )
FT_USE_MODULE( FT_Renderer_Class, ft_raster1_renderer_class )
FT_USE_MODULE( FT_Module_Class, sfnt_module_class )
FT_USE_MODULE( FT_Renderer_Class, ft_smooth_renderer_class )
"#;

fn build_vendored() {
    let src = wasm_vendor_dir("freetype");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());

    let config_dir = out_dir.join("ftconfig/freetype/config");
    std::fs::create_dir_all(&config_dir).expect("failed to create FreeType config dir");
    std::fs::write(config_dir.join("ftmodule.h"), FTMODULE_H)
        .expect("failed to write FreeType module list");

    let mut cfg = cc::Build::new();
    cfg.warnings(false)
        .define("FT2_BUILD_LIBRARY", "1")
        // Our trimmed module list, which has to come before the stock include
        // directory so it wins the lookup for freetype/config/ftmodule.h.
        .include(out_dir.join("ftconfig"))
        .include(src.join("include"));

    for file in FREETYPE_SOURCES {
        cfg.file(src.join(file));
    }

    cfg.compile("freetype");

    println!(
        "cargo:include-path={}",
        src.join("include").to_str().unwrap()
    );
    println!("cargo:rerun-if-changed={}", src.display());
}

fn main() {
    if target_is_wasm() {
        build_vendored();
        return;
    }

    let cfg = Configuration::default();
    let dep = Dependency::probe(Freetype2Spec, &cfg);

    // This is the key. What we print here will be propagated into depending
    // crates' build scripts as the environment variable DEP_FREETYPE2_INCLUDE_PATH,
    // allowing them to find the headers internally. If/when we start vendoring
    // FreeType, this can become $OUT_DIR.
    let mut sep = "cargo:include-path=";

    dep.foreach_include_path(|p| {
        print!("{}{}", sep, p.to_str().unwrap());
        sep = ";";
    });

    println!();

    dep.emit();
}
