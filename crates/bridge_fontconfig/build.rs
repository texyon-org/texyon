//! fontconfig build script. On normal targets we always find it externally. A
//! wasm target has no system fonts at all, so the crate provides the API itself
//! (see `src/wasm_stub.rs`) and only the headers have to be conjured up here.

use std::{env, fs, path::PathBuf};
use tectonic_dep_support::{target_is_wasm, Configuration, Dependency, Spec};

struct FontconfigSpec;

impl Spec for FontconfigSpec {
    fn get_pkgconfig_spec(&self) -> &str {
        "fontconfig"
    }

    fn get_vcpkg_spec(&self) -> &[&str] {
        &["fontconfig"]
    }
}

/// Enough of `fontconfig.h` for `tectonic_xetex_layout.h`, which includes it on
/// non-macOS targets. Every real fontconfig call lives in Rust.
const FONTCONFIG_H: &str = r#"/* Generated by tectonic_bridge_fontconfig's build script for the wasm build.
 *
 * The wasm target has no system fontconfig. Font discovery is answered in Rust
 * (tectonic_bridge_fontconfig::wasm_stub), so all the C needs is the types.
 */
#ifndef TECTONIC_WASM_FONTCONFIG_H
#define TECTONIC_WASM_FONTCONFIG_H

typedef int FcBool;
typedef unsigned char FcChar8;
typedef struct _FcPattern FcPattern;
typedef struct _FcConfig FcConfig;
typedef struct _FcObjectSet FcObjectSet;

typedef struct _FcFontSet {
    int nfont;
    int sfont;
    FcPattern **fonts;
} FcFontSet;

#endif /* TECTONIC_WASM_FONTCONFIG_H */
"#;

fn emit_wasm_headers() {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let include_dir = out_dir.join("include");
    let dest = include_dir.join("fontconfig");

    fs::create_dir_all(&dest).expect("failed to create include dir");
    fs::write(dest.join("fontconfig.h"), FONTCONFIG_H).expect("failed to write fontconfig.h");

    println!("cargo:include-path={}", include_dir.display());
}

fn main() {
    if target_is_wasm() {
        emit_wasm_headers();
        return;
    }

    // Find any necessary deps.

    let dep_cfg = Configuration::default();
    let dep = Dependency::probe(FontconfigSpec, &dep_cfg);

    // This is the key. What we print here will be propagated into depending
    // crates' build scripts as the environment variable DEP_FONTCONFIG_INCLUDE_PATH,
    // allowing them to find the headers internally. If/when we start vendoring
    // FreeType, this can become $OUT_DIR.
    let mut sep = "cargo:include-path=";

    dep.foreach_include_path(|p| {
        print!("{}{}", sep, p.to_str().unwrap());
        sep = ";";
    });

    println!();

    dep.emit();
}
