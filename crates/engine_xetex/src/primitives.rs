/// Extra setup `initialize_primitives` runs after defining a primitive.
#[derive(Copy, Clone)]
pub(crate) enum PrimInit {
    None,
    Par,
    Write,
    /// Copy the definition to this frozen eqtb location.
    Frozen(crate::units::CsId),
}

#[derive(Copy, Clone)]
pub(crate) struct PrimitiveDef {
    pub name: &'static str,
    pub cmd: Cmd,
    pub chr: i32,
    pub init: PrimInit,
}

const fn p(name: &'static str, cmd: Cmd, chr: i32) -> PrimitiveDef {
    PrimitiveDef {
        name,
        cmd,
        chr,
        init: PrimInit::None,
    }
}

const fn int_par(n: IntPar) -> PrimitiveDef {
    match n.name() {
        Some(name) => p(name, Cmd::AssignInt, n.loc().raw()),
        None => panic!("parameter without a primitive"),
    }
}

const fn dimen_par(n: DimenPar) -> PrimitiveDef {
    p(n.name(), Cmd::AssignDimen, n.loc().raw())
}

const fn code_table(t: CodeTable) -> PrimitiveDef {
    p(t.name(), Cmd::DefCode, t.raw())
}

const fn xetex_code(name: &'static str, c: XetexCode) -> PrimitiveDef {
    p(name, Cmd::XetexDefCode, c.raw())
}

const fn shape(loc: ShapeLoc) -> PrimitiveDef {
    p(loc.name(), Cmd::SetShape, loc.raw())
}

const fn tok_par(n: TokPar) -> PrimitiveDef {
    p(n.name(), Cmd::AssignToks, n.loc().raw())
}

const fn glue_par(n: GluePar) -> PrimitiveDef {
    p(n.name(), Cmd::AssignGlue, n.loc().raw())
}

const fn mu_glue_par(n: GluePar) -> PrimitiveDef {
    p(n.name(), Cmd::AssignMuGlue, n.loc().raw())
}

/// A primitive named after its `chr_code` enum variant.
macro_rules! code {
    ($cmd:expr, $code:expr) => {
        p($code.name(), $cmd, $code.raw())
    };
}

impl PrimitiveDef {
    const fn init(self, init: PrimInit) -> PrimitiveDef {
        PrimitiveDef { init, ..self }
    }
}

