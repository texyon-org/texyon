//! ICU build script.
//!
//! We find it externally, and probably will continue to do so for as long as
//! this crate is needed. Vendoring the ICU library is almost certainly not
//! something that one should do.
//!
//! wasm is the exception, since there is nothing external to find. There the
//! crate implements the API in Rust (`src/wasm_shim.rs`) and this script only
//! has to produce the headers XeTeX's remaining C includes, and clear the
//! symbol-version suffix that the Rust `#[link_name]`s interpolate.

use std::{env, fs, path::PathBuf};
use tectonic_dep_support::{target_is_wasm, Backend, Configuration, Dependency, Spec};

struct IcuSpec;

impl Spec for IcuSpec {
    fn get_pkgconfig_spec(&self) -> &str {
        "icu-uc"
    }

    fn get_vcpkg_spec(&self) -> &[&str] {
        &["icu"]
    }
}

/// Enough of `<unicode/utypes.h>` and `<unicode/platform.h>` for XeTeX's
/// remaining C to compile.
///
/// `xetex-core.h` includes both, but the two translation units left in C never
/// name an ICU type — all the real calls are Rust.
const UTYPES_H: &str = r#"/* Generated by tectonic_bridge_icu's build script for the wasm build. */
#ifndef TECTONIC_WASM_UTYPES_H
#define TECTONIC_WASM_UTYPES_H

#include <stdint.h>

typedef uint16_t UChar;
typedef int32_t UChar32;
typedef int8_t UBool;
typedef int32_t UErrorCode;

#define U_ZERO_ERROR 0
#define U_SUCCESS(code) ((code) <= U_ZERO_ERROR)
#define U_FAILURE(code) ((code) > U_ZERO_ERROR)

#endif /* TECTONIC_WASM_UTYPES_H */
"#;

/// wasm is little-endian, always.
const PLATFORM_H: &str = r#"/* Generated by tectonic_bridge_icu's build script for the wasm build. */
#ifndef TECTONIC_WASM_UPLATFORM_H
#define TECTONIC_WASM_UPLATFORM_H

#define U_IS_BIG_ENDIAN 0

#endif /* TECTONIC_WASM_UPLATFORM_H */
"#;

fn emit_wasm_headers() {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let include_dir = out_dir.join("include");
    let dest = include_dir.join("unicode");

    fs::create_dir_all(&dest).expect("failed to create include dir");
    fs::write(dest.join("utypes.h"), UTYPES_H).expect("failed to write utypes.h");
    fs::write(dest.join("platform.h"), PLATFORM_H).expect("failed to write platform.h");

    println!("cargo:include-path={}", include_dir.display());

    // The Rust shim exports plain `ubidi_open` rather than `ubidi_open_76`, so
    // dependents must interpolate nothing into their #[link_name]s.
    println!("cargo:version-suffix=");
}

fn main() {
    if target_is_wasm() {
        emit_wasm_headers();
        return;
    }

    let target = std::env::var("TARGET").unwrap();
    let cfg = Configuration::default();
    let dep = Dependency::probe(IcuSpec, &cfg);

    // This is the key. What we print here will be propagated into depending
    // crates' build scripts as the environment variable DEP_ICUUC_INCLUDE_PATH,
    // allowing them to find the headers internally.

    let mut sep = "cargo:include-path=";

    dep.foreach_include_path(|p| {
        print!("{}{}", sep, p.to_str().unwrap());
        sep = ";";
    });

    println!();

    dep.emit();

    // vcpkg-rs is not guaranteed to emit libraries in the order required by a
    // single-pass linker, so we might need to make sure that's done right.

    if cfg.backend == Backend::Vcpkg && target.contains("-linux-") {
        // add icudata to the end of the list of libs as vcpkg-rs
        // does not order individual libraries as a single pass
        // linker requires.
        println!("cargo:rustc-link-lib=icudata");
    }
}
