#!/usr/bin/env bash
# Fetch the C libraries that Tectonic normally picks up from the system.
#
# A browser has no system libpng/FreeType/Graphite2, so the wasm build compiles
# them from source alongside the rest of the engine. Sources land in
# tools/wasm/vendor/ (gitignored); the bridge crates' build scripts look there
# whenever the target family is wasm.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENDOR="$HERE/vendor"
mkdir -p "$VENDOR"

LIBPNG_VERSION=1.6.50
FREETYPE_VERSION=2.13.3
GRAPHITE2_VERSION=1.3.14
MUPDF_VERSION=1.24.9

fetch() {
    local name="$1" url="$2" strip_dir="$3"
    if [ -d "$VENDOR/$name" ]; then
        echo "== $name: already present, skipping"
        return
    fi
    echo "== $name: fetching $url"
    local tmp
    tmp="$(mktemp -d)"
    curl -fsSL --retry 3 -o "$tmp/src.tar.gz" "$url"
    mkdir -p "$VENDOR/$name"
    tar xzf "$tmp/src.tar.gz" -C "$VENDOR/$name" --strip-components="$strip_dir"
    rm -rf "$tmp"
    echo "== $name: ok"
}

fetch libpng \
    "https://github.com/pnggroup/libpng/archive/refs/tags/v${LIBPNG_VERSION}.tar.gz" 1
# The GitHub mirror, because savannah's mirror redirector periodically hands
# out HTML with status 200. Only include/ is consumed, which the tag carries.
fetch freetype \
    "https://github.com/freetype/freetype/archive/refs/tags/VER-$(echo "$FREETYPE_VERSION" | tr . -).tar.gz" 1
fetch graphite2 \
    "https://github.com/silnrsi/graphite/archive/refs/tags/${GRAPHITE2_VERSION}.tar.gz" 1

# MuPDF, for the SVG renderer behind the live preview. Optional: it is only
# needed for the `backend-mupdf` feature, it is 145 MB of source, and its terms
# are AGPL rather than the MIT the rest of this tree uses. Pass --with-mupdf to
# opt in.
if [ "${WITH_MUPDF:-}" = "1" ] || [ "${1:-}" = "--with-mupdf" ]; then
    fetch mupdf \
        "https://mupdf.com/downloads/archive/mupdf-${MUPDF_VERSION}-source.tar.gz" 1

    # WASI has no mkstemp; see the patch for what that costs (nothing we use).
    if ! grep -q "__wasi__" "$VENDOR/mupdf/source/fitz/document.c"; then
        patch -p1 -d "$VENDOR/mupdf" < "$HERE/patches/mupdf-no-mkstemp.patch"
    fi

    echo "== mupdf: building for wasm32-wasip1 (this takes a few minutes)"
    # shellcheck source=/dev/null
    . "$HERE/env.sh"

    # MuPDF bundles its own FreeType, HarfBuzz and zlib, and Tectonic has its
    # own of each.
    # Two FreeTypes in one wasm module is not a link error we would notice --
    # RUSTFLAGS carries --allow-multiple-definition for the allocator shim -- it
    # is a silent pick of whichever came first, with one library's structs
    # reaching the other's code. HarfBuzz showed exactly that: Tectonic's
    # hb_font_create resolved to MuPDF's hb_face_set_user_data, whose allocator
    # wants a MuPDF context that does not exist on that path, and the module
    # trapped. So MuPDF is built against Tectonic's copies instead: one
    # FreeType, one HarfBuzz, one zlib, no ambiguity.
    #
    # That leaves the pdf_* namespace, which MuPDF and Tectonic's pdf_io both
    # occupy. The other targets separate them with `objcopy --redefine-syms`,
    # which llvm-objcopy does not implement for wasm, so the renaming happens in
    # the preprocessor instead: every pdf_* MuPDF defines gets a #define, applied
    # to MuPDF's own sources and to the shim that calls into it.
    mupdf_make() {
        make -C "$VENDOR/mupdf" -j"$(nproc)" \
            OS=wasi build=release \
            CC="$WASI_SDK/bin/clang" CXX="$WASI_SDK/bin/clang++" \
            AR="$WASI_SDK/bin/llvm-ar" RANLIB="$WASI_SDK/bin/llvm-ranlib" \
            XCFLAGS="--target=wasm32-wasip1 --sysroot=$WASI_SYSROOT -mllvm -wasm-enable-sjlj -DTOFU_CJK -DFZ_ENABLE_JS=0 -DFZ_ENABLE_OCR_OUTPUT=0 $1" \
            USE_SYSTEM_FREETYPE=yes \
            SYS_FREETYPE_CFLAGS="-I$VENDOR/freetype/include" SYS_FREETYPE_LIBS="" \
            USE_SYSTEM_ZLIB=yes \
            SYS_ZLIB_CFLAGS="-I$VENDOR/mupdf/thirdparty/zlib" SYS_ZLIB_LIBS="" \
            USE_SYSTEM_HARFBUZZ=yes \
            SYS_HARFBUZZ_CFLAGS="-I$HERE/../../crates/bridge_harfbuzz/harfbuzz/src" SYS_HARFBUZZ_LIBS="" \
            HAVE_X11=no HAVE_GLUT=no HAVE_CURL=no HAVE_LIBCRYPTO=no \
            HAVE_TESSERACT=no HAVE_LEPTONICA=no HAVE_OBJCOPY=no \
            libs
    }

    # Pass one: build so there is an archive to read the pdf_* names out of.
    if [ ! -f "$VENDOR/mupdf/build/release/libmupdf.a" ]; then
        mupdf_make ""
    fi

    RENAME_HEADER="$VENDOR/mupdf/tectonic-pdf-rename.h"
    "$WASI_SDK/bin/llvm-nm" -g --defined-only \
        "$VENDOR/mupdf/build/release/libmupdf.a" 2>/dev/null \
        | awk '$2 ~ /^[TDBRSW]$/ && $3 ~ /^pdf_/ {print $3}' \
        | sort -u \
        | awk 'BEGIN { print "/* Generated by tools/wasm/fetch-deps.sh. */" }
               { printf "#define %s tectonic_mupdf_%s\n", $1, $1 }' \
        > "$RENAME_HEADER"

    if [ ! -s "$RENAME_HEADER" ]; then
        echo "mupdf: could not enumerate pdf_* symbols to rename" >&2
        exit 1
    fi
    echo "== mupdf: renaming $(grep -c '^#define' "$RENAME_HEADER") pdf_* symbols"

    # Pass two: rebuild from clean with the renames and the shared libraries.
    make -C "$VENDOR/mupdf" build=release OS=wasi clean >/dev/null 2>&1 || true
    mupdf_make "-include $RENAME_HEADER"

    echo "== mupdf: ok"
fi

# libpng ships its build-time config as a template; the stock one is what every
# distro uses, so just install it.
if [ ! -f "$VENDOR/libpng/pnglibconf.h" ]; then
    cp "$VENDOR/libpng/scripts/pnglibconf.h.prebuilt" "$VENDOR/libpng/pnglibconf.h"
fi

echo
echo "Vendored sources are in $VENDOR"
