#!/usr/bin/env bash
# Build a static MuPDF for the native `preview-mupdf` backend on Linux and macOS.
#
# The result lands in tools/mupdf/vendor/mupdf (gitignored) with the same layout
# as the wasm build, and preview_render's build script links it when
# TEXYON_MUPDF_DIR points there. Windows links vcpkg's libmupdf instead.
#
# MuPDF is built against Tectonic's FreeType, HarfBuzz and zlib so the binary
# carries one copy of each, and its pdf_* symbols are renamed in the
# preprocessor so they cannot collide with pdf_io's (see tools/wasm/fetch-deps.sh).
#
# Environment:
#   MUPDF_TARBALL     local source tarball, instead of downloading it
#   FREETYPE_CFLAGS   defaults to `pkg-config --cflags freetype2`
#   ZLIB_CFLAGS       defaults to `pkg-config --cflags zlib`
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$HERE/../.."
MUPDF_VERSION=1.24.9
SRC="$HERE/vendor/mupdf"

if [ ! -d "$SRC" ]; then
    tmp="$(mktemp -d)"
    tarball="${MUPDF_TARBALL:-}"
    if [ -z "$tarball" ]; then
        tarball="$tmp/src.tar.gz"
        curl -fsSL --retry 3 -o "$tarball" \
            "https://mupdf.com/downloads/archive/mupdf-${MUPDF_VERSION}-source.tar.gz"
    fi
    mkdir -p "$SRC"
    tar xzf "$tarball" -C "$SRC" --strip-components=1
    rm -rf "$tmp"
fi

FREETYPE_CFLAGS="${FREETYPE_CFLAGS:-$(pkg-config --cflags freetype2)}"
ZLIB_CFLAGS="${ZLIB_CFLAGS:-$(pkg-config --cflags zlib 2>/dev/null || true)}"
HARFBUZZ_CFLAGS="-I$ROOT/crates/bridge_harfbuzz/harfbuzz/src"
JOBS="$(getconf _NPROCESSORS_ONLN)"

case "$(uname -s)" in
    Darwin) symbol_prefix=_ ;;
    *) symbol_prefix= ;;
esac

mupdf_make() {
    make -C "$SRC" -j"$JOBS" build=release \
        XCFLAGS="-fPIC -DTOFU_CJK -DFZ_ENABLE_JS=0 -DFZ_ENABLE_OCR_OUTPUT=0 $1" \
        USE_SYSTEM_FREETYPE=yes SYS_FREETYPE_CFLAGS="$FREETYPE_CFLAGS" SYS_FREETYPE_LIBS="" \
        USE_SYSTEM_ZLIB=yes SYS_ZLIB_CFLAGS="$ZLIB_CFLAGS" SYS_ZLIB_LIBS="" \
        USE_SYSTEM_HARFBUZZ=yes SYS_HARFBUZZ_CFLAGS="$HARFBUZZ_CFLAGS" SYS_HARFBUZZ_LIBS="" \
        HAVE_X11=no HAVE_GLUT=no HAVE_CURL=no HAVE_LIBCRYPTO=no \
        HAVE_TESSERACT=no HAVE_LEPTONICA=no HAVE_OBJCOPY=no \
        libs
}

RENAME_HEADER="$SRC/tectonic-pdf-rename.h"
MUPDF_LIB="$SRC/build/release/libmupdf.a"

raw_pdf_symbols() {
    nm -g --defined-only "$1" 2>/dev/null \
        | awk -v p="^${symbol_prefix}pdf_" '$2 ~ /^[TDBRSW]$/ && $3 ~ p {print $3}' \
        | sed "s/^${symbol_prefix}//" | sort -u
}

if [ -f "$MUPDF_LIB" ] && [ -s "$RENAME_HEADER" ] && [ -z "$(raw_pdf_symbols "$MUPDF_LIB")" ]; then
    echo "== mupdf: already built with renamed symbols"
    exit 0
fi

make -C "$SRC" build=release clean >/dev/null 2>&1 || true
mupdf_make ""

{
    echo "/* Generated by tools/mupdf/build.sh. */"
    raw_pdf_symbols "$MUPDF_LIB" | awk '{ printf "#define %s texyon_mupdf_%s\n", $1, $1 }'
} > "$RENAME_HEADER"
count="$(grep -c '^#define' "$RENAME_HEADER" || true)"
if [ "$count" -eq 0 ]; then
    echo "mupdf: could not enumerate pdf_* symbols to rename" >&2
    exit 1
fi
echo "== mupdf: renaming $count pdf_* symbols"

make -C "$SRC" build=release clean >/dev/null 2>&1 || true
mupdf_make "-include $RENAME_HEADER"

if [ -n "$(raw_pdf_symbols "$MUPDF_LIB")" ]; then
    echo "mupdf: the renamed archive still exports raw pdf_* symbols" >&2
    exit 1
fi
echo "== mupdf: ok ($SRC)"
